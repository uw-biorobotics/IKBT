import unittest


def _robot(name):
    '''Load a robot with the FK chatter suppressed.'''
    import contextlib
    import io
    from ikbtfunctions.ik_driver import load_robot
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        return load_robot(name)


class TestSolver022(unittest.TestCase):
    '''Numerical IK:  the callables, the residual, and convergence.

       These tests take ~1.5 s once the FK pickles are warm.  The FIRST run
       after this file is added takes minutes, because it is the first thing in
       the test suite ever to load Craig417 and Raven-II -- the two robots whose
       alpha is not a multiple of pi/2 -- and their forward kinematics has to
       be computed and cached.  That is a one-off, not a regression.'''

    def setUp(self):
        print('\n\n===============  Test numeric_ik  =====================')
        return

    def runTest(self):
        self.test_nikA_pvals_resolves_the_string_entries()
        self.test_nikB_fk_matches_the_independent_oracle()
        self.test_nikC_pose_error_is_zero_at_the_target()
        self.test_nikD_rotation_angle_axis_edge_cases()
        self.test_nikE_converges_from_a_perturbed_exact_solution()
        self.test_nikF_jacobian_predicts_the_pose_change()
        self.test_nikG_convergence_is_quadratic()
        self.test_nikH_survives_the_wrist_singularity()
        self.test_nikI_sub_six_dof_arm()

    #  ---------------------------------------------------------------- pvals

    def test_nikA_pvals_resolves_the_string_entries(self):
        '''Craig417 and Raven-II are the two robots whose pvals carry invented
           ca_i/sa_i entries, and those symbols really do appear in T_06 -- so
           they must be RESOLVED to numbers.  dh_analysis.numeric_pvals() drops
           a non-numeric one, which would leave ca1 as a free symbol and a
           spurious lambdify argument.  (kin_cl has evaluated them since
           2026-09-03;  this asserts the property rather than the mechanism, so
           it still holds if the string fallback is ever taken.)'''

        fs = ' numeric_ik pvals FAIL'
        for name in ('Craig417', 'Raven-II'):
            M, R, unks = _robot(name)
            pv = pvals_numeric(M)
            for k, v in pv.items():
                self.assertTrue(np.isfinite(v),
                                fs + ' (%s: %s is not finite)' % (name, k))
            #  the whole point: T_06 has nothing left over
            left = sp.Matrix(M.T_06).subs(pv).free_symbols - set(joint_symbols(M))
            self.assertEqual(left, set(),
                             fs + ' (%s left %s unresolved)'
                             % (name, sorted(str(s) for s in left)))

        #  and a clean robot is unaffected
        M, R, unks = _robot('Puma')
        self.assertEqual(len(pvals_numeric(M)), len(M.pvals), fs + ' (Puma)')

    #  ------------------------------------------------------------------- FK

    def test_nikB_fk_matches_the_independent_oracle(self):
        '''The lambdified T_06 must agree with dh_analysis's pure-numpy Link_N
           chain.  Two independent paths to the same matrix is cheap insurance:
           a sign error or a transposed link would otherwise show up much later
           as "the numerics do not converge".'''

        fs = ' numeric_ik FK-vs-oracle FAIL'
        rng = np.random.RandomState(0)

        for name in ('Puma', 'KinovaLite', 'Craig417', 'ICP5p5_A21'):
            M, R, unks = _robot(name)
            ndof = dof_of(M)
            fk = fk_callable(M, ndof)
            rows, slots, kinds, defaulted = da.compile_rows(M.DH, M.pvals,
                                                            M.vv, ndof)
            for _ in range(4):
                q = [rng.uniform(-np.pi, np.pi) if k == 'rot'
                     else rng.uniform(-1.0, 1.0) for k in kinds]
                #  oracle: write the joint values into their DH slots
                rr = rows.copy()
                for r, (jr, jc) in enumerate(slots):
                    rr[jr, jc] = q[r]
                T_oracle = np.asarray(da.fk_numeric(rr, ndof), dtype=float)
                T_lam = fk(q)
                err = np.max(np.abs(T_lam - T_oracle))
                self.assertLess(err, 1e-9,
                                fs + ' (%s: max elementwise error %g)'
                                % (name, err))

    #  --------------------------------------------------------------- metric

    def test_nikC_pose_error_is_zero_at_the_target(self):
        fs = ' numeric_ik pose_error FAIL'
        M, R, unks = _robot('Puma')
        fk = fk_callable(M)
        q = [0.3, -0.4, 0.5, 0.6, -0.7, 0.8]
        T = fk(q)
        e, m = pose_error(T, T)
        self.assertLess(np.max(np.abs(e)), 1e-12, fs + ' (residual not zero)')
        self.assertLess(m, 1e-12, fs + ' (metric not zero)')

        #  a pure translation of 0.1 must read as exactly 0.1
        T2 = T.copy()
        T2[0, 3] += 0.1
        e, m = pose_error(T, T2)
        self.assertAlmostEqual(m, 0.1, places=9,
                               msg=fs + ' (translation not measured in length units)')

        #  a pure rotation of 0.2 rad must read as w_rot * 0.2
        c, s = np.cos(0.2), np.sin(0.2)
        Rz = np.array([[c, -s, 0], [s, c, 0], [0, 0, 1.0]])
        T3 = T.copy()
        T3[:3, :3] = Rz @ T[:3, :3]
        e, m = pose_error(T, T3, w_rot=3.0)
        self.assertAlmostEqual(m, 3.0 * 0.2, places=9,
                               msg=fs + ' (w_rot not applied to the angle)')

    def test_nikD_rotation_angle_axis_edge_cases(self):
        '''Identity and the theta = pi case, which is where the skew part
           vanishes and a naive axis extraction divides by zero.'''

        fs = ' numeric_ik angle/axis FAIL'
        th, ax = rotation_angle_axis(np.eye(3))
        self.assertEqual(th, 0.0, fs + ' (identity should be 0)')
        self.assertLess(np.linalg.norm(ax), 1e-15, fs + ' (identity axis)')

        #  exactly pi about x
        Rpi = np.diag([1.0, -1.0, -1.0])
        th, ax = rotation_angle_axis(Rpi)
        self.assertAlmostEqual(th, np.pi, places=6, msg=fs + ' (pi angle)')
        self.assertAlmostEqual(abs(ax[0]), 1.0, places=6,
                               msg=fs + ' (pi axis should be +-x, got %s)' % ax)

        #  round trip a known rotation
        for angle in (0.05, 0.7, 2.5, np.pi - 1e-3):
            c, s = np.cos(angle), np.sin(angle)
            Rz = np.array([[c, -s, 0], [s, c, 0], [0, 0, 1.0]])
            th, ax = rotation_angle_axis(Rz)
            self.assertAlmostEqual(th, angle, places=6,
                                   msg=fs + ' (angle %g)' % angle)
            self.assertAlmostEqual(abs(ax[2]), 1.0, places=6,
                                   msg=fs + ' (axis for %g)' % angle)

    #  ----------------------------------------------------------- the solver

    def test_nikE_converges_from_a_perturbed_exact_solution(self):
        '''The core claim.  Take a pose generated BY the FK, perturb the joints,
           and confirm the solver walks back to that pose.

           Uses a pose the arm can certainly reach, so a failure here is the
           solver's and not the target's.'''

        fs = ' numeric_ik convergence FAIL'
        rng = np.random.RandomState(7)

        for name, w in (('Puma', 1.0), ('KinovaLite', 1000.0)):
            M, R, unks = _robot(name)
            fk = fk_callable(M)
            jac = jacobian_callable(M)

            #  scale the tolerance to the model:  1e-9 m on a metre robot is
            #  1e-6 mm on a millimetre one, which is not the same demand.
            tol = 1e-8 * max(1.0, w)

            q_true = np.array([0.4, -0.6, 0.7, 0.9, -0.5, 0.3])
            T_d = fk(q_true)

            for trial in range(3):
                q0 = q_true + rng.uniform(-0.15, 0.15, 6)
                res = solve_numeric(fk, jac, q0, T_d, w_rot=w, tol=tol,
                                    max_iter=200)
                self.assertTrue(res['converged'],
                                fs + ' (%s trial %d: metric %g after %d iters, %s)'
                                % (name, trial, res['metric'],
                                   res['iterations'], res['reason']))
                #  the metric must be monotone non-increasing -- LM rejects
                #  any step that would make it worse
                h = res['history']
                self.assertTrue(all(h[i + 1] <= h[i] + 1e-12
                                    for i in range(len(h) - 1)),
                                fs + ' (%s: metric went UP)' % name)

    def test_nikF_jacobian_predicts_the_pose_change(self):
        '''J_0 must actually be the derivative of the pose, in the base frame.

           Checked by finite difference, because a Jacobian in the WRONG FRAME
           still looks plausible -- it has the right size and it changes with q
           -- and would show up only as slow or failed convergence.  This is the
           test that catches a missing blkdiag(R,R).'''

        fs = ' numeric_ik Jacobian FAIL'
        M, R, unks = _robot('Puma')
        fk = fk_callable(M)
        jac = jacobian_callable(M)

        q = np.array([0.35, -0.55, 0.65, 0.85, -0.45, 0.25])
        T0 = fk(q)
        J0 = jacobian_base(T0, jac(q))

        h = 1e-7
        for i in range(6):
            dq = np.zeros(6)
            dq[i] = h
            T1 = fk(q + dq)

            #  finite-difference twist, base frame
            dp = (T1[:3, 3] - T0[:3, 3]) / h
            th, ax = rotation_angle_axis(T1[:3, :3] @ T0[:3, :3].T)
            dw = (th / h) * ax

            self.assertLess(np.linalg.norm(dp - J0[:3, i]), 1e-4,
                            fs + ' (column %d translation: fd %s vs J %s)'
                            % (i, dp, J0[:3, i]))
            self.assertLess(np.linalg.norm(dw - J0[3:, i]), 1e-4,
                            fs + ' (column %d rotation: fd %s vs J %s)'
                            % (i, dw, J0[3:, i]))


    def test_nikG_convergence_is_quadratic(self):
        """The error must roughly SQUARE each step near the solution.

           This is what distinguishes a real Gauss-Newton step from any old
           descent direction:  a wrong-but-plausible Jacobian (mis-scaled, or
           in the wrong frame) still converges, just linearly.  Measured
           sequence on Puma:  1.9e-01  1.6e-02  3.4e-04  1.0e-07  2.3e-15."""

        fs = ' numeric_ik quadratic FAIL'
        M, R, unks = _robot('Puma')
        fk, jac = fk_callable(M), jacobian_callable(M)
        q_true = np.array([0.4, -0.6, 0.7, 0.9, -0.5, 0.3])
        T_d = fk(q_true)
        q0 = q_true + np.array([.15, -.12, .1, .13, -.11, .09])

        res = solve_numeric(fk, jac, q0, T_d, w_rot=1.0, tol=1e-13,
                            max_iter=60)
        self.assertTrue(res['converged'], fs + ' (did not converge)')
        h = [x for x in res['history'] if x > 0]
        self.assertGreaterEqual(len(h), 4, fs + ' (too few steps to judge)')

        #  e_{k+1} <= C e_k^2 over the middle of the run.  Loose C, because the
        #  point is the ORDER, not the constant.
        ok = 0
        for i in range(1, len(h) - 1):
            if h[i + 1] <= 100.0 * h[i] ** 2 + 1e-14:
                ok += 1
        self.assertGreaterEqual(ok, 2,
                                fs + ' (no quadratic steps in %s)'
                                % ['%.1e' % x for x in h])

    def test_nikH_survives_the_wrist_singularity(self):
        """th_5 = 0 makes Puma joints 4 and 6 colinear, so J loses rank and an
           undamped Newton step is singular by construction.  Damped least
           squares must still get there -- this is the whole reason the plan
           specified LM rather than plain gradient descent."""

        fs = ' numeric_ik singularity FAIL'
        M, R, unks = _robot('Puma')
        fk, jac = fk_callable(M), jacobian_callable(M)

        q_s = np.array([0.3, -0.5, 0.6, 0.7, 0.0, 0.2])   # th_5 = 0
        T_d = fk(q_s)

        #  confirm the premise: the Jacobian really is rank-deficient there
        J = jacobian_base(fk(q_s), jac(q_s))
        self.assertLess(np.linalg.matrix_rank(J, tol=1e-9), 6,
                        fs + ' (test premise: J should be singular at th_5=0)')

        rng = np.random.RandomState(3)
        for t in range(4):
            q0 = q_s + rng.uniform(-0.1, 0.1, 6)
            res = solve_numeric(fk, jac, q0, T_d, w_rot=1.0, tol=1e-9,
                                max_iter=300)
            self.assertTrue(res['converged'],
                            fs + ' (trial %d: metric %g, %s)'
                            % (t, res['metric'], res['reason']))

    def test_nikI_sub_six_dof_arm(self):
        """A 4-DOF table padded to 6 rows must use 4 joints, not 6.

           ICP5p5_A21 is the case:  dof_of() must say 4, the Jacobian must be
           6x4 (J66 is stored 6x6 with NON-zero surplus columns), and a
           reachable target must still converge."""

        fs = ' numeric_ik sub-6-DOF FAIL'
        M, R, unks = _robot('ICP5p5_A21')
        n = dof_of(M)
        self.assertEqual(n, 4, fs + ' (dof_of said %d)' % n)

        fk, jac = fk_callable(M), jacobian_callable(M)
        q = np.array([0.3, 0.2, 0.4, 0.5])
        self.assertEqual(jac(q).shape, (6, 4),
                         fs + ' (Jacobian should be 6x%d)' % n)

        T_d = fk(q)
        res = solve_numeric(fk, jac, q + 0.1, T_d, w_rot=1.0, tol=1e-9,
                            max_iter=200)
        self.assertTrue(res['converged'],
                        fs + ' (reachable target: metric %g)' % res['metric'])


