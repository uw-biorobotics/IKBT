#!/usr/bin/python
#
#   numeric_ik.py --  numerical inverse kinematics by damped least squares
#
#   The numeric half of the hybrid method.  The hybrid solves a SIMPLIFIED arm
#   in closed form and then corrects the answer numerically against the TRUE
#   arm's forward kinematics.  This module is the correction step, and it is
#   deliberately standalone:  it takes an FK callable, a Jacobian callable, a
#   seed and a target pose, and knows nothing about behavior trees, blackboards
#   or the hybrid branch.  That is what lets it be validated on robots which
#   already solve exactly -- perturb a known-good solution, confirm it comes
#   back -- before any of it is wired into the tree.
#
#   WHY DAMPED LEAST SQUARES (Levenberg-Marquardt) rather than plain gradient
#   descent:  dq = J'(JJ' + lam^2 I)^-1 e behaves like Newton away from
#   singularities and degrades GRACEFULLY to gradient descent as lam grows,
#   which is exactly the failure mode a 6R arm hits at a wrist singularity.
#   Plain gradient descent would make that failure permanent.
#
#   ------------------------------------------------------------------------
#   THREE THINGS MEASURED BEFORE WRITING THIS, two of which contradict the plan:
#
#   1. T_06 (4x4) and J66 (6x6) are ALREADY PICKLED for all 32 robots, and
#      their free symbols are exactly the joint variables plus params that
#      appear in pvals.  No new symbolic computation is needed here.
#
#   2. SUM-OF-ANGLE SYMBOLS CANNOT APPEAR in T_06 or J66.  The plan says they do
#      and must be resolved from R.kequation_aux_list first.  Measured, no robot
#      in the set has one -- but the reason is structural, not statistical (BH):
#      EVERY LINK CAN HAVE ONLY ONE JOINT VARIABLE, so a DH-derived link
#      transform has nothing for a th_23 to be.  SOA terms arise WITHIN the FK
#      equations as the sum-of-angles scan rewrites them, and that rewriting
#      lands in the MATRIX EQUATIONS (matrix_equation.Ts) -- not in the product
#      T_06 or in J66, which stay in raw joint variables.
#
#      So this is a property to rely on, not a measurement to re-check when
#      robot 33 arrives.  (BH notes a sum-of-angle simplification *candidate*
#      could in principle show up in a Jacobian term;  finding it would be of
#      minimal benefit, so nothing here looks for one.)
#
#   3. pvals USED NOT TO BE UNIFORMLY NUMERIC, and the pair of robots involved
#      is not the pair the plan names.  Measured over all 32:  Craig417 and
#      Raven-II, not Raven-II and ICP5p5_A21 -- those two are the only ones
#      whose alpha is not a multiple of pi/2, so they are the only ones for
#      which forward_kinematics() invents ca_i/sa_i at all.  It used to write
#      the STRINGS 'np.cos(al_1)' / 'np.sin(pi/4)' into pvals, and those
#      symbols really are in T_06 -- so they had to be RESOLVED, not skipped.
#      dh_analysis.numeric_pvals() DROPS them, which is right for its own
#      zero-tests and wrong here:  a dropped ca1 survives as a free symbol and
#      becomes a spurious lambdify argument.
#
#      forward_kinematics() now evaluates them (2026-09-03), so every pval on
#      every robot is a number.  pvals_numeric() below stays as the guard: the
#      string is still the fallback for an alpha whose symbols have no numeric
#      value, and _lambdify_checked() refuses anything left over.
#   ------------------------------------------------------------------------
#   MEASURED, on Puma, seeded by perturbing a pose generated by its own FK:
#
#       perturbation   converged   mean iterations
#          0.05 rad      10/10           3.0
#          0.20 rad      10/10           4.0
#          0.50 rad      10/10           5.6
#          1.00 rad      10/10          10.2
#          2.00 rad      10/10          19.2
#
#   and the error sequence is quadratic, which is what says the step is a real
#   Gauss-Newton step and not merely a descent direction:
#
#       1.9e-01  1.6e-02  3.4e-04  1.0e-07  2.3e-15
#
#   At the Puma WRIST SINGULARITY (th_5 = 0, joints 4 and 6 colinear) it still
#   converged 10/10 -- which is the damping earning its place;  an undamped
#   Newton step is singular there by construction.
#   ------------------------------------------------------------------------
#
#   Copyright 2026 University of Washington
#
#   Developed by Blake Hannaford
#   BioRobotics Lab, University of Washington

import numpy as np
import sympy as sp

import ikbtbasics.dh_analysis as da


#  Weight on the orientation error, in the model's LENGTH UNITS per radian.
#
#  BH's convergence metric is  ||dp|| + (1 metre) * theta,  which needs to know
#  what a metre is in the model -- and NOTHING IN THE REPO RECORDS A ROBOT'S
#  UNITS.  Measured, they are not even consistent:  Puma is in metres
#  (a_2 = 0.432) while KinovaLite is in millimetres (l_2 = 280, d_5 = 57).  So
#  there is no single correct constant, and guessing one would silently
#  under-weight orientation by 1000x on half the robot set.
#
#  Hence: w_rot is an explicit parameter everywhere, defaulting to "one model
#  length unit per radian".  For BH's 1 m/rad, pass 1.0 on a metre model and
#  1000.0 on a millimetre model.  See w_rot_for() for a unit-free alternative.
W_ROT_DEFAULT = 1.0


###############################################################################
#
#    Turning a pickled Mech into numeric callables
#

def pvals_numeric(M):
    '''Every entry of M.pvals as a float, with the 'np.cos(...)' strings
       RESOLVED rather than dropped.

       Returns {Symbol: float}.  Raises ValueError naming any entry that could
       not be reduced to a number, because a silently-missing param becomes an
       extra lambdify argument and then a confusing arity error a long way from
       here.

       Since 2026-09-03 forward_kinematics() evaluates ca_i/sa_i, so in
       practice there is nothing left to resolve;  the string remains its
       fallback for an alpha whose symbols have no numeric value.  Such a
       string references either another pvals entry ('np.cos(al_1)', Raven-II)
       or a literal ('np.sin(pi/4)', Craig417), so it is resolved AFTER the
       plainly-numeric entries are known.  Two passes, because one string could
       in principle reference another.'''

    raw = dict(M.pvals or {})
    out = {}

    #  Pass 1: the entries that are already numbers.
    leftover = {}
    for k, v in raw.items():
        if isinstance(v, str):
            leftover[k] = v
            continue
        try:
            out[sp.sympify(k)] = float(v)
        except (TypeError, ValueError):
            leftover[k] = v

    #  Pass 2 (and 3): resolve the rest against what is known so far.
    for _ in range(2):
        if not leftover:
            break
        still = {}
        for k, v in leftover.items():
            expr = v
            if isinstance(expr, str):
                #  'np.cos(al_1)' -> 'cos(al_1)';  sympify maps pi to sp.pi.
                expr = expr.replace('np.', '')
            try:
                e = sp.sympify(expr).subs(out)
                out[sp.sympify(k)] = float(e)
            except (TypeError, ValueError, sp.SympifyError):
                still[k] = v
        if len(still) == len(leftover):
            break                      # made no progress; stop looping
        leftover = still

    if leftover:
        raise ValueError('pvals_numeric: could not reduce to numbers: %s'
                         % {str(k): v for k, v in leftover.items()})
    return out


def dof_of(M, maxrows=6):
    '''How many joints this arm really has.

       The DH table is ALWAYS 6 rows -- shorter arms are padded with [0,0,0,0]
       (see CLAUDE.md, "Adding a robot") -- so 6 is the table's height, not the
       arm's DOF.  Counting the leading rows whose joint cell carries a symbol
       gives the real number:  measured, Craig417 and ICP5p5_A21 are 4-DOF
       tables padded to 6.

       This must NOT be taken from the unknown list.  kinematics_pickle()
       extends that list with sum-of-angle variables, so Craig417 reports 5
       unknowns for 4 joints.'''

    n = 0
    for r in range(maxrows):
        (jr, jc), kind = da.joint_cell(M.DH, M.vv, r)
        if not sp.sympify(M.DH[jr, jc]).free_symbols:
            break                      # padding starts here
        n = r + 1
    return n


def joint_symbols(M, ndof=None):
    '''The joint variables in CHAIN ORDER, one per real DH row.

       Read from the DH table via dh_analysis.joint_cell() rather than from
       R.variables, for two reasons:  the unknown list has been EXTENDED with
       sum-of-angle variables (th_23) which are not joint variables, and the DH
       table is what actually fixes the order a q vector must be in.'''

    if ndof is None:
        ndof = dof_of(M)
    syms = []
    for r in range(ndof):
        (jr, jc), kind = da.joint_cell(M.DH, M.vv, r)
        cell = sp.sympify(M.DH[jr, jc])
        #  THE CELL IS NOT ALWAYS THE BARE JOINT VARIABLE.  Wrist's DH table
        #  holds 'B + pi/2' and 'C + pi/2':  the constant is a fixed part of
        #  the mechanism and the JOINT is the symbol inside.  Returning the
        #  whole cell made T_06's free symbols {A,B,C} fail to match
        #  {A, B+pi/2, C+pi/2}, so _lambdify_checked() rejected Wrist outright
        #  -- and the code generators would have named a joint 'B + pi/2'.
        fs = sorted(cell.free_symbols, key=str)
        if len(fs) != 1:
            raise ValueError('joint_symbols: DH row %d joint cell %s does not '
                             'contain exactly one joint variable' % (r, cell))
        syms.append(fs[0])
    return syms


def _lambdify_checked(expr_matrix, syms, what):
    '''lambdify, after proving nothing is left un-substituted.

       A leftover free symbol is the failure this guards:  lambdify would
       happily accept it as a positional argument, and the caller would then be
       passing joint angles into a link-length slot.

       NOTE THE NESTED [syms].  Passing the symbol list wrapped in another list
       tells lambdify to generate a function of ONE sequence argument, which
       unpacks it itself:

           def _lambdifygenerated(_Dummy_34):
               [th_1, th_2, a_2] = _Dummy_34
               return ...

       so the returned callable already takes a q vector and no wrapper is
       needed to spread it.  (The flat form, lambdify(syms, ...), makes one
       parameter per symbol;  it allows per-argument numpy broadcasting, which
       nothing here wants -- every call evaluates a single joint vector.)'''

    extra = sorted((expr_matrix.free_symbols - set(syms)), key=str)
    if extra:
        raise ValueError('numeric_ik: %s still contains %s -- pvals did not '
                         'resolve every parameter' % (what, [str(s) for s in extra]))
    return sp.lambdify([syms], expr_matrix, 'numpy')


def fk_callable(M, ndof=None):
    '''q -> 4x4 homogeneous transform, as pure numpy.  len(q) == dof_of(M).'''
    pv = pvals_numeric(M)
    syms = joint_symbols(M, ndof)
    return _lambdify_checked(sp.Matrix(M.T_06).subs(pv), syms, 'T_06')


def jacobian_callable(M, ndof=None):
    '''q -> 6 x ndof Jacobian EXPRESSED IN FRAME 6 (that is what J66 is).

       ONLY THE FIRST ndof COLUMNS.  J66 is stored 6x6 for every robot, even a
       4-DOF one, and measured, the surplus columns are NOT zero:  a padded DH
       row still gets a Jacobian column computed for it, as though the constant
       0 in its joint cell were a joint.  Handing those to the solver would let
       it "move" joints the arm does not have.

       Use jacobian_base() to rotate the result into the base frame, which is
       where the pose error lives.'''
    if ndof is None:
        ndof = dof_of(M)
    pv = pvals_numeric(M)
    syms = joint_symbols(M, ndof)
    J = sp.Matrix(M.J66).subs(pv)[:, :ndof]
    return _lambdify_checked(J, syms, 'J66')


def jacobian_base(T, J66):
    '''J_0 = blkdiag(R_06, R_06) . J_66.

       J66 is expressed in frame 6;  the residual is expressed in the base
       frame, so the two must be brought into the same frame or every step is
       rotated by an arbitrary amount.'''

    R = np.asarray(T)[:3, :3]
    Z = np.zeros((3, 3))
    Rot = np.vstack([np.hstack([R, Z]), np.hstack([Z, R])])
    return Rot @ np.asarray(J66)


###############################################################################
#
#    The residual and the metric
#

def rotation_angle_axis(Rerr):
    '''(theta, axis) of a rotation matrix, theta in [0, pi].

       Returns axis = [0,0,0] when theta is 0, so theta*axis is a usable
       rotation vector with no special case at the caller.

       The two degenerate cases are handled explicitly rather than left to
       arccos:  near theta = 0 the axis is numerically meaningless (and the
       rotation vector vanishes anyway), and near theta = pi the skew part
       vanishes so the axis has to come from the symmetric part instead.'''

    Rerr = np.asarray(Rerr, dtype=float)
    c = (np.trace(Rerr) - 1.0) / 2.0
    c = min(1.0, max(-1.0, c))                 # arccos domain, always
    theta = float(np.arccos(c))

    if theta < 1e-12:
        return 0.0, np.zeros(3)

    if theta < np.pi - 1e-6:
        axis = np.array([Rerr[2, 1] - Rerr[1, 2],
                         Rerr[0, 2] - Rerr[2, 0],
                         Rerr[1, 0] - Rerr[0, 1]]) / (2.0 * np.sin(theta))
        return theta, axis

    #  theta ~ pi:  the skew part is ~0, so use  R + I = 2 a a'  and take the
    #  best-conditioned column.
    Msym = Rerr + np.eye(3)
    j = int(np.argmax(np.linalg.norm(Msym, axis=0)))
    axis = Msym[:, j]
    n = np.linalg.norm(axis)
    if n < 1e-12:
        return theta, np.zeros(3)
    return theta, axis / n


def pose_error(T, T_d, w_rot=W_ROT_DEFAULT):
    '''(residual, metric) between the current pose T and the target T_d.

       residual is the 6-vector  [dp ; w_rot * theta * axis]  used by the LM
       step.  metric is BH's scalar  ||dp|| + w_rot * theta,  which is what
       convergence is reported and thresholded on.

       The SAME rotation parameterisation and the SAME weight appear in both,
       which is the point:  the step and the stopping test then agree about what
       "closer" means.  The metric is linear in the error rather than
       quadratic-ish, so one threshold means the same thing near and far from
       convergence -- which is why it is this and not a Frobenius norm.'''

    T = np.asarray(T, dtype=float)
    T_d = np.asarray(T_d, dtype=float)

    dp = T_d[:3, 3] - T[:3, 3]
    theta, axis = rotation_angle_axis(T_d[:3, :3] @ T[:3, :3].T)

    residual = np.concatenate([dp, w_rot * theta * axis])
    metric = float(np.linalg.norm(dp) + w_rot * theta)
    return residual, metric


def w_rot_for(M, ndof=6):
    '''A unit-free w_rot:  one characteristic arm length per radian.

       An alternative to picking a physical metre when the model's units are
       unknown -- it says "a radian of orientation error costs about as much as
       being one arm-length away", which is scale-invariant and therefore
       behaves the same on the metre robots and the millimetre ones.  It is NOT
       BH's 1 m/rad;  it is offered for the case where the caller does not know
       the units and wants something defensible.'''

    return float(da.length_scale(M.DH, M.pvals, M.vv, ndof))


###############################################################################
#
#    The solver
#

def solve_numeric(fk, jac, q0, T_d, w_rot=W_ROT_DEFAULT, tol=1e-9,
                  max_iter=100, lam0=1e-3, lam_min=1e-12, lam_max=1e12):
    '''Refine the seed q0 so that fk(q) matches T_d.  Damped least squares.

           fk    q -> 4x4        (from fk_callable)
           jac   q -> 6x6 in frame 6  (from jacobian_callable)

       Returns a dict:  q, metric, iterations, converged, history, reason.

       Never raises on a bad step:  a singular solve or a non-finite FK is
       treated as a REJECTED step, which raises lam and tries again.  That is
       the whole reason for damping, and turning it into an exception would
       make the singularity failure mode fatal rather than graceful.

       The rotation rows of the Jacobian are scaled by w_rot to match the
       residual, whose rotation block is scaled the same way.  Weighting one and
       not the other would solve a different problem than the one being
       measured.'''

    q = np.array(q0, dtype=float).flatten()
    lam = float(lam0)
    I6 = np.eye(6)
    #  6 x ndof.  For ndof < 6 the system is under-determined -- the arm cannot
    #  reach a general 6-DOF pose -- and damped least squares then returns the
    #  best achievable step rather than failing.  That is the correct behaviour,
    #  but it means `converged` can legitimately stay False on such an arm.
    ndof = q.size
    W = np.diag([1.0, 1.0, 1.0, w_rot, w_rot, w_rot])

    def measure(qq):
        T = fk(qq)
        if not np.all(np.isfinite(T)):
            return None, np.inf
        return pose_error(T, T_d, w_rot=w_rot)

    e, m = measure(q)
    history = [m]
    reason = 'max_iter'

    for it in range(max_iter):
        if m <= tol:
            reason = 'converged'
            break

        T = fk(q)
        try:
            J = W @ jacobian_base(T, jac(q))
            A = J @ J.T + (lam ** 2) * I6
            dq = J.T @ np.linalg.solve(A, e)
        except np.linalg.LinAlgError:
            lam = min(lam * 10.0, lam_max)
            if lam >= lam_max:
                reason = 'lam_max'
                break
            continue

        if not np.all(np.isfinite(dq)):
            lam = min(lam * 10.0, lam_max)
            if lam >= lam_max:
                reason = 'lam_max'
                break
            continue

        q_try = q + dq
        e_try, m_try = measure(q_try)

        if m_try < m:
            q, e, m = q_try, e_try, m_try
            lam = max(lam / 3.0, lam_min)
        else:
            lam = min(lam * 3.0, lam_max)
            if lam >= lam_max:
                reason = 'lam_max'
                break

        history.append(m)

    return {'q': q,
            'metric': m,
            'iterations': len(history) - 1,
            'converged': bool(m <= tol),
            'reason': reason if m > tol else 'converged',
            'history': history}


