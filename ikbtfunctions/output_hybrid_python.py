import unittest


class TestSolver024(unittest.TestCase):
    '''The hybrid code generator.

       Two properties, and both are about a COPY staying honest.  This module
       emits kinematics and an algorithm into a standalone file;  nothing else
       in IKBT then reads that file, so an error in it is invisible to every
       other test.  These two compare the emitted thing against the tested
       thing it was copied from.'''

    def setUp(self):
        print('\n\n===============  Test hybrid code generator  =====================')
        return

    def runTest(self):
        self.test_hgA_generated_fk_matches_the_library()
        self.test_hgB_generated_refine_matches_the_library()
        self.test_hgC_expr_py_refuses_what_it_cannot_emit()

    #  Puma, because it solves exactly and its pickle is always warm.  The
    #  generator does not care that Puma is not a hybrid robot:  what is under
    #  test is the emitted kinematics, not which branch produced them.
    def puma(self):
        import io as _io
        import contextlib as _cl
        from ikbtfunctions.ik_robots import robot_params
        from ikbtbasics.ik_classes import kinematics_pickle

        buf = _io.StringIO()
        with _cl.redirect_stdout(buf):
            dh, vv, params, pvals, unks = robot_params('Puma')
            M, R, unks = kinematics_pickle('Puma', dh, params, pvals, vv,
                                           unks, False)
        return M

    def test_hgA_generated_fk_matches_the_library(self):
        '''The EMITTED fk/jacobian must agree with numeric_ik's lambdified ones.

           Phase II refines against the generated FK, so if that FK is not the
           true arm's, the method converges confidently on the wrong pose --
           and every check downstream that uses the same generated FK would
           agree with it.  This is the one comparison against an independent
           construction of the same kinematics.'''
        import importlib.util
        import tempfile
        import numpy as np

        fs = ' hybrid codegen FK FAIL'
        M = self.puma()

        with tempfile.TemporaryDirectory() as d:
            path = write_fk_module(M, 'Puma', jacobian=True, dirname=d)
            spec = importlib.util.spec_from_file_location('gen_fk_puma', path)
            gen = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(gen)

            fk_ref = nik.fk_callable(M)
            jac_ref = nik.jacobian_callable(M)

            self.assertEqual(gen.JOINT_NAMES,
                             [str(s) for s in nik.joint_symbols(M)],
                             fs + ' (joint order differs from numeric_ik)')

            rng = np.random.default_rng(20260902)
            for _ in range(8):
                q = list(rng.uniform(-2.0, 2.0, gen.NDOF))
                dT = np.max(np.abs(np.asarray(gen.fk_Puma(q), dtype=float)
                                   - np.asarray(fk_ref(q), dtype=float)))
                dJ = np.max(np.abs(np.asarray(gen.jacobian_Puma(q), dtype=float)
                                   - np.asarray(jac_ref(q), dtype=float)))
                self.assertLess(dT, 1e-9, fs + ' (FK differs by %g)' % dT)
                self.assertLess(dJ, 1e-9, fs + ' (Jacobian differs by %g)' % dJ)

    def test_hgB_generated_refine_matches_the_library(self):
        '''REFINE_CORE must solve identically to numeric_ik.solve_numeric().

           The generated module cannot import ikbtbasics -- it stands on numpy
           alone -- so the damped-least-squares loop is emitted as a copy of
           the library one.  A copy that drifts is worse than no copy:  the
           library stays green while what ships to users quietly stops
           converging.  This runs both on the same problem from the same seed
           and requires the same answer.'''
        import numpy as np

        fs = ' hybrid codegen refine FAIL'
        M = self.puma()
        fk = nik.fk_callable(M)
        jac = nik.jacobian_callable(M)
        ndof = nik.dof_of(M)
        w_rot = 1.0                      # Puma is in metres

        #  Exec the emitted source in a bare namespace.  numpy and W_ROT are
        #  all the generated module gives it, so that is all it gets here --
        #  a missing name would otherwise be masked by this file's globals.
        ns = {'np': np, 'W_ROT': w_rot}
        exec(REFINE_CORE, ns)
        self.assertIn('solve_numeric', ns, fs + ' (REFINE_CORE emitted no solver)')

        q_true = np.array([0.4, -0.6, 0.7, 0.9, -0.5, 0.3][:ndof])
        T_d = np.asarray(fk(q_true), dtype=float)

        rng = np.random.default_rng(24)
        for k in range(4):
            seed = list(q_true + rng.uniform(-0.3, 0.3, ndof))
            ref = nik.solve_numeric(fk, jac, seed, T_d, w_rot=w_rot)
            got = ns['solve_numeric'](fk, jac, seed, T_d, w_rot=w_rot)

            self.assertEqual(bool(got['converged']), bool(ref['converged']),
                             fs + ' (seed %d: converged differs)' % k)
            self.assertEqual(got['iterations'], ref['iterations'],
                             fs + ' (seed %d: iteration count differs, %d vs %d)'
                             % (k, got['iterations'], ref['iterations']))
            dq = float(np.max(np.abs(np.asarray(got['q']) - np.asarray(ref['q']))))
            self.assertLess(dq, 1e-12,
                            fs + ' (seed %d: answers differ by %g)' % (k, dq))

