    #  defaulted in the numerics.  BH's metric is ||dp|| + (1 m)*theta, but
    #  nothing records a model's units and they are not consistent across the
    #  robot set -- Puma is in metres (a_2 = 0.432), KinovaLite in millimetres
    #  (l_2 = 280).  w_rot_for() sidesteps that with a unit-free choice: one
    #  characteristic arm length per radian, which behaves the same on both.
    w_rot = nik.w_rot_for(M_true, ndof)

